// Self-contained SHA-256 and HMAC-SHA256 in TypeScript.
//
// Why hand-rolled: the app signs every command to the PC with
// HMAC-SHA256(secret, "ts.nonce.action"), and the signature must match the Go
// service byte-for-byte. Keeping the implementation here means no native
// dependency, it works fully offline, and it's verified against the server's
// scheme in tests. Inputs here are small (tens of bytes), so speed is a non-issue.

